import os
import sys
from datetime import datetime, timezone

import streamlit as st

# Allow imports when running locally or on Streamlit Cloud.
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, PROJECT_ROOT)

from config import CATEGORIES_ALLOWED

# ---------------------------------------------------------
# STREAMLIT PAGE CONFIG
# ---------------------------------------------------------

st.set_page_config(
    page_title="Tender Intelligence Agent",
    page_icon="🎯",
    layout="wide",
    initial_sidebar_state="expanded",
)

LIVE_DATA_FILE = os.path.join(PROJECT_ROOT, "data", "live_tenders.json")
HEALTH_LOG_FILE = os.path.join(PROJECT_ROOT, "system_health.log")

